def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False

def compute_metrics(preds, labels):
    acc = accuracy_score(labels, preds)
    f1 = f1_score(labels, preds, average='binary', zero_division=0)
    return acc, f1

def save_checkpoint(model, optimizer, epoch, filename):
    os.makedirs(os.path.dirname(filename), exist_ok=True)
    torch.save({
        'epoch': epoch,
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict() if optimizer else None,
    }, filename)

# ------------------------- DATASET 1: Brain Stroke CT (Kaggle) -------------------------
class StrokeCTDataset(Dataset):
    def __init__(self, split='train', img_size=(128, 128)):
        self.img_size = img_size
        self.split = split
        self.data_dir = self._get_dataset_path()
        self.image_paths, self.labels = self._load_dataset()
        print(f"[CT] {split}: {len(self.image_paths)} images (Stroke: {self.labels.count(1)}, Normal: {self.labels.count(0)})")

    def _get_dataset_path(self):
        if os.path.exists("/kaggle/input/brain-stroke-ct-image-dataset"):
            return "/kaggle/input/brain-stroke-ct-image-dataset"
        os.makedirs(Config.data_dir, exist_ok=True)
        extract_path = os.path.join(Config.data_dir, "brain_stroke_ct")
        if os.path.exists(extract_path) and len(os.listdir(extract_path)) > 0:
            return extract_path
        print("Downloading Brain Stroke CT dataset from Kaggle...")
        try:
            path = kagglehub.dataset_download("afridirahman/brain-stroke-ct-image-dataset")
        except Exception as e:
            raise RuntimeError(f"Failed to download CT dataset: {e}")
        zip_files = glob.glob(os.path.join(path, "*.zip"))
        if zip_files:
            with zipfile.ZipFile(zip_files[0], 'r') as zip_ref:
                zip_ref.extractall(extract_path)
            return extract_path
        return path

    def _label_from_path(self, path):
        p = path.lower()
        # Check for Brain_Data_Organised structure
        if "brain_data_organised" in p:
            if "normal" in p:
                return 0
            if "stroke" in p:
                return 1
        # Fallback: check filename
        if "normal" in p:
            return 0
        if "stroke" in p:
            return 1
        return None

    def _load_dataset(self):
        if not os.path.exists(self.data_dir):
            raise FileNotFoundError(f"CT dataset not found at {self.data_dir}.")

        image_paths, labels = [], []
        valid_ext = ('.jpg', '.jpeg', '.png')

        for root, _, files in os.walk(self.data_dir):
            for f in files:
                if not f.lower().endswith(valid_ext):
                    continue
                full_path = os.path.join(root, f)
                label = self._label_from_path(full_path)
                if label is None:
                    continue
                image_paths.append(full_path)
                labels.append(label)

        if len(image_paths) == 0:
            raise FileNotFoundError(f"No labeled images found in {self.data_dir}.")

        indices = list(range(len(image_paths)))
        np.random.seed(42)
        np.random.shuffle(indices)
        split_idx = int(0.8 * len(indices))
        indices = indices[:split_idx] if self.split == 'train' else indices[split_idx:]
        return [image_paths[i] for i in indices], [labels[i] for i in indices]

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_path = self.image_paths[idx]
        label = self.labels[idx]
        try:
            img = Image.open(img_path).convert('L')
            img = img.resize(self.img_size, Image.Resampling.LANCZOS)
            img = np.array(img, dtype=np.float32) / 255.0
            img = np.repeat(img[np.newaxis, :, :], 3, axis=0)
            img = torch.from_numpy(img)
        except Exception as e:
            print(f"Error loading {img_path}: {e}")
            img = torch.zeros(3, *self.img_size, dtype=torch.float32)
        return img, torch.tensor(label, dtype=torch.long)

