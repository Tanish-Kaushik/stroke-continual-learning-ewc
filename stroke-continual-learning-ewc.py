# ------------------------- REPLAY BUFFER -------------------------
class ReplayBuffer:
    def __init__(self, capacity=200):
        self.capacity = capacity
        self.buffer = deque(maxlen=capacity)

    def push(self, x, y):
        self.buffer.append((x.cpu(), y.cpu()))

    def sample(self, batch_size):
        batch = random.sample(self.buffer, min(len(self.buffer), batch_size))
        x_batch, y_batch = zip(*batch)
        x_batch = torch.stack(x_batch, dim=0)
        y_batch = torch.tensor(y_batch, dtype=torch.long)
        return x_batch, y_batch

    def __len__(self):
        return len(self.buffer)

# ------------------------- EWC -------------------------
class EWC:
    def __init__(self, model, dataloader, device, fisher_sample_size=200):
        self.model = model
        self.device = device
        self.fisher_sample_size = fisher_sample_size
        self.params = {n: p for n, p in model.named_parameters() if p.requires_grad}
        self._means = {}
        self._precision_matrices = {}
        self._compute_fisher(dataloader)

    def _compute_fisher(self, dataloader):
        for n, p in self.params.items():
            self._precision_matrices[n] = torch.zeros_like(p)
            self._means[n] = p.data.clone()

        self.model.eval()
        sample_data = []
        for i, (x, y) in enumerate(dataloader):
            if i * dataloader.batch_size >= self.fisher_sample_size:
                break
            sample_data.append((x, y))

        for x, y in sample_data:
            x, y = x.to(self.device), y.to(self.device)
            self.model.zero_grad()
            output = self.model(x)
            loss = nn.functional.cross_entropy(output, y)
            loss.backward()
            for n, p in self.params.items():
                if p.grad is not None:
                    self._precision_matrices[n] += p.grad.data ** 2 / len(sample_data)

        for n in self.params:
            self._precision_matrices[n] = self._precision_matrices[n].to(self.device)

    def penalty(self, model):
        loss = 0
        for n, p in model.named_parameters():
            if n in self._precision_matrices:
                loss += (self._precision_matrices[n] * (p - self._means[n]) ** 2).sum()
        return loss

# ------------------------- TRAINING FUNCTIONS -------------------------
def evaluate(model, dataloader, config):
    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for x, y in dataloader:
            x = x.to(config.device)
            out = model(x)
            pred = out.argmax(dim=1).cpu()
            all_preds.extend(pred.numpy())
            all_labels.extend(y.numpy())
    acc, _ = compute_metrics(all_preds, all_labels)
    return acc

def train_baseline(model, train_loader, val_loader, config, epochs):
    optimizer = torch.optim.Adam(model.parameters(), lr=config.lr, weight_decay=config.weight_decay)
    criterion = nn.CrossEntropyLoss()
    history = {'train_acc': [], 'val_acc': [], 'train_loss': []}
    for epoch in range(epochs):
        model.train()
        running_loss, correct, total = 0.0, 0, 0
        for x, y in tqdm(train_loader, desc=f'Baseline Epoch {epoch+1}'):
            x, y = x.to(config.device), y.to(config.device)
            optimizer.zero_grad()
            out = model(x)
            loss = criterion(out, y)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
            correct += (out.argmax(1) == y).sum().item()
            total += y.size(0)
        train_acc = correct / total
        val_acc = evaluate(model, val_loader, config)
        history['train_acc'].append(train_acc)
        history['val_acc'].append(val_acc)
        history['train_loss'].append(running_loss / len(train_loader))
        print(f"Epoch {epoch+1}: Train Acc {train_acc:.4f}, Val Acc {val_acc:.4f}")
    return history

def train_ewc(model, train_loader, val_loader, config, epochs, ewc, ewc_lambda):
    optimizer = torch.optim.Adam(model.parameters(), lr=config.lr, weight_decay=config.weight_decay)
    criterion = nn.CrossEntropyLoss()
    history = {'train_acc': [], 'val_acc': [], 'train_loss': []}
    for epoch in range(epochs):
        model.train()
        running_loss, correct, total = 0.0, 0, 0
        for x, y in tqdm(train_loader, desc=f'EWC Epoch {epoch+1}'):
            x, y = x.to(config.device), y.to(config.device)
            optimizer.zero_grad()
            out = model(x)
            loss = criterion(out, y) + ewc_lambda * ewc.penalty(model)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
            correct += (out.argmax(1) == y).sum().item()
            total += y.size(0)
        train_acc = correct / total
        val_acc = evaluate(model, val_loader, config)
        history['train_acc'].append(train_acc)
        history['val_acc'].append(val_acc)
        history['train_loss'].append(running_loss / len(train_loader))
        print(f"EWC Epoch {epoch+1}: Train Acc {train_acc:.4f}, Val Acc {val_acc:.4f}")
    return history

def train_replay(model, train_loader, val_loader, config, epochs, buffer):
    optimizer = torch.optim.Adam(model.parameters(), lr=config.lr, weight_decay=config.weight_decay)
    criterion = nn.CrossEntropyLoss()
    history = {'train_acc': [], 'val_acc': [], 'train_loss': []}
    for epoch in range(epochs):
        model.train()
        running_loss, correct, total = 0.0, 0, 0
        for x, y in tqdm(train_loader, desc=f'Replay Epoch {epoch+1}'):
            x, y = x.to(config.device), y.to(config.device)
            optimizer.zero_grad()
            if len(buffer) > 0:
                x_replay, y_replay = buffer.sample(config.replay_batch_size)
                x_replay, y_replay = x_replay.to(config.device), y_replay.to(config.device)
                x = torch.cat([x, x_replay], dim=0)
                y = torch.cat([y, y_replay], dim=0)
            out = model(x)
            loss = criterion(out, y)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
            correct += (out.argmax(1) == y).sum().item()
            total += y.size(0)
            for xi, yi in zip(x[:x.size(0)//2], y[:y.size(0)//2]):
                buffer.push(xi, yi)
        train_acc = correct / total
        val_acc = evaluate(model, val_loader, config)
        history['train_acc'].append(train_acc)
        history['val_acc'].append(val_acc)
        history['train_loss'].append(running_loss / len(train_loader))
        print(f"Replay Epoch {epoch+1}: Train Acc {train_acc:.4f}, Val Acc {val_acc:.4f}")
    return history

def train_ewc_replay(model, train_loader, val_loader, config, epochs, ewc, buffer, ewc_lambda):
    optimizer = torch.optim.Adam(model.parameters(), lr=config.lr, weight_decay=config.weight_decay)
    criterion = nn.CrossEntropyLoss()
    history = {'train_acc': [], 'val_acc': [], 'train_loss': []}
    for epoch in range(epochs):
        model.train()
        running_loss, correct, total = 0.0, 0, 0
        for x, y in tqdm(train_loader, desc=f'EWC+Replay Epoch {epoch+1}'):
            x, y = x.to(config.device), y.to(config.device)
            optimizer.zero_grad()
            if len(buffer) > 0:
                x_replay, y_replay = buffer.sample(config.replay_batch_size)
                x_replay, y_replay = x_replay.to(config.device), y_replay.to(config.device)
                x = torch.cat([x, x_replay], dim=0)
                y = torch.cat([y, y_replay], dim=0)
            out = model(x)
            loss = criterion(out, y) + ewc_lambda * ewc.penalty(model)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
            correct += (out.argmax(1) == y).sum().item()
            total += y.size(0)
            for xi, yi in zip(x[:x.size(0)//2], y[:y.size(0)//2]):
                buffer.push(xi, yi)
        train_acc = correct / total
        val_acc = evaluate(model, val_loader, config)
        history['train_acc'].append(train_acc)
        history['val_acc'].append(val_acc)
        history['train_loss'].append(running_loss / len(train_loader))
        print(f"EWC+Replay Epoch {epoch+1}: Train Acc {train_acc:.4f}, Val Acc {val_acc:.4f}")
    return history

