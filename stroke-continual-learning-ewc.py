    plt.savefig(os.path.join(config.plot_dir, 'avg_accuracy.png'), dpi=200)
    plt.close()
    print(f"Saved: avg_accuracy.png")

    # Backward Transfer
    bwt_values = []
    for strat in config.strategies:
        acc_task0_after_task0 = results[strat][0][0]
        acc_task0_after_task1 = results[strat][1][0]
        bwt = acc_task0_after_task1 - acc_task0_after_task0
