    plt.figure(figsize=(9, 6))
    labels = [config.strategy_labels[s] for s in config.strategies]
    colors = [config.strategy_colors[s] for s in config.strategies]
    bars = plt.bar(labels, bwt_values, color=colors, edgecolor='black')
