class ISLES2022Dataset(Dataset):
    """ISLES-2022 with REAL labels from lesion masks."""
    def __init__(self, split='train', img_size=(128, 128)):
        self.img_size = img_size
        self.split = split
        self.data_dir = os.path.join(Config.data_dir, "isles2022")
        self._download_dataset()
        self.image_paths, self.labels = self._load_dataset()
        print(f"[ISLES] {split}: {len(self.image_paths)} volumes (Lesion: {self.labels.count(1)}, No Lesion: {self.labels.count(0)})")

    def _download_dataset(self):
        marker = os.path.join(self.data_dir, ".download_complete")
        if os.path.exists(marker):
            return
        os.makedirs(self.data_dir, exist_ok=True)
        url = "https://zenodo.org/records/7960856/files/ISLES-2022.zip"
        print("Downloading ISLES-2022 (this may take ~10 min)...")
        zip_path = os.path.join(self.data_dir, "ISLES-2022.zip")
        try:
            response = requests.get(url, stream=True)
            response.raise_for_status()
            total_size = int(response.headers.get('content-length', 0))
            with open(zip_path, 'wb') as f:
                with tqdm(total=total_size, unit='B', unit_scale=True, desc="ISLES-2022") as pbar:
                    for chunk in response.iter_content(chunk_size=1024*1024):
                        f.write(chunk)
                        pbar.update(len(chunk))
            with zipfile.ZipFile(zip_path, 'r') as zip_ref:
                zip_ref.extractall(self.data_dir)
            os.remove(zip_path)
            with open(marker, 'w') as f:
                f.write("ok")
        except Exception as e:
            raise RuntimeError(f"Failed to download ISLES-2022: {e}")

    def _load_dataset(self):
        """Find raw volumes and their corresponding lesion masks. Label = 1 if lesion exists."""
        if not os.path.exists(self.data_dir):
            raise FileNotFoundError(f"ISLES-2022 not found at {self.data_dir}.")

        raw_paths, mask_paths = [], []
        for root, _, files in os.walk(self.data_dir):
            # Skip derivatives folder (contains masks)
            if "derivatives" in root:
                continue
            for f in files:
                if f.lower().endswith(('.nii.gz', '.nii')):
                    full_path = os.path.join(root, f)
                    raw_paths.append(full_path)

        # Find corresponding masks
        mask_dir = os.path.join(self.data_dir, "derivatives")
        if os.path.exists(mask_dir):
            for root, _, files in os.walk(mask_dir):
                for f in files:
                    if f.lower().endswith(('.nii.gz', '.nii')):
                        mask_paths.append(os.path.join(root, f))

        print(f"Found {len(raw_paths)} raw volumes, {len(mask_paths)} masks")

        # Match raw volumes to masks by subject ID
        raw_by_subject = {}
        for r in raw_paths:
            subj = os.path.basename(os.path.dirname(r))
            raw_by_subject.setdefault(subj, []).append(r)

        mask_by_subject = {}
        for m in mask_paths:
            # Extract subject ID from mask path
            parts = m.split(os.sep)
            for p in parts:
                if p.startswith("sub-"):
                    subj = p
                    break
            mask_by_subject.setdefault(subj, []).append(m)

        samples = []
        for subj in raw_by_subject:
            raw_vols = raw_by_subject[subj]
            masks = mask_by_subject.get(subj, [])
            if masks:
                # Use first mask (DWI lesion mask)
                mask_path = masks[0]
            else:
                mask_path = None
            for rv in raw_vols:
                samples.append((rv, mask_path))

        if len(samples) == 0:
            raise FileNotFoundError(f"No samples found in {self.data_dir}.")

        # Load labels from masks
        image_paths, labels = [], []
        for raw_path, mask_path in samples:
            image_paths.append(raw_path)
            if mask_path is None:
                labels.append(0)
            else:
                try:
                    mask_data = nib.load(mask_path).get_fdata()
                    labels.append(1 if np.any(mask_data > 0) else 0)
                except Exception as e:
                    print(f"Warning: Could not read mask {mask_path}: {e}")
                    labels.append(0)

        # Split
        indices = list(range(len(image_paths)))
        np.random.seed(42)
        np.random.shuffle(indices)
        split_idx = int(0.8 * len(indices))
        indices = indices[:split_idx] if self.split == 'train' else indices[split_idx:]
        return [image_paths[i] for i in indices], [labels[i] for i in indices]

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        nii_path = self.image_paths[idx]
        label = self.labels[idx]
        try:
            vol = nib.load(nii_path).get_fdata(dtype=np.float32)
            mid = vol.shape[2] // 2
            slice_2d = vol[:, :, mid]
            lo, hi = np.percentile(slice_2d, 1), np.percentile(slice_2d, 99)
            if hi - lo < 1e-6:
                hi = slice_2d.max() if slice_2d.max() > 0 else 1.0
                lo = 0.0
            slice_2d = np.clip((slice_2d - lo) / (hi - lo + 1e-8), 0, 1)
            img = Image.fromarray((slice_2d * 255).astype(np.uint8))
            img = img.resize(self.img_size, Image.Resampling.LANCZOS)
            arr = np.array(img, dtype=np.float32) / 255.0
            arr = np.repeat(arr[np.newaxis, :, :], 3, axis=0)
            img = torch.from_numpy(arr)
        except Exception as e:
            print(f"Error loading {nii_path}: {e}")
            img = torch.zeros(3, *self.img_size, dtype=torch.float32)
        return img, torch.tensor(label, dtype=torch.long)

