    plt.ylabel('Backward Transfer (BWT)')
    plt.xlabel('Strategy')
    plt.title('Forgetting Measure (BWT) – Real Results')
    plt.legend()
    plt.grid(alpha=0.3, axis='y')
    plt.tight_layout()
    plt.savefig(os.path.join(config.plot_dir, 'backward_transfer.png'), dpi=200)
    plt.close()
    print(f"Saved: backward_transfer.png")

    print("\n📈 KEY RESULTS:")
    for strat, bwt in zip(config.strategies, bwt_values):
        print(f"  {config.strategy_labels[strat]:<15} BWT = {bwt:+.3f}")

    return bwt_values

