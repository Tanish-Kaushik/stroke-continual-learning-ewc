class StrokeCNN(nn.Module):
    def __init__(self, num_classes=2, pretrained=True):
        super().__init__()
        self.backbone = models.resnet18(weights='DEFAULT' if pretrained else None)
        in_features = self.backbone.fc.in_features
        self.backbone.fc = nn.Linear(in_features, num_classes)

    def forward(self, x):
        return self.backbone(x)

# ------------------------- REPLAY BUFFER -------------------------
class ReplayBuffer:
    def __init__(self, capacity=200):
        self.capacity = capacity
        self.buffer = deque(maxlen=capacity)

    def push(self, x, y):
        self.buffer.append((x.detach().cpu(), y.detach().cpu()))

    def sample(self, batch_size):
        if len(self.buffer) == 0:
            return None, None
        batch = random.sample(self.buffer, min(len(self.buffer), batch_size))
        x_batch, y_batch = zip(*batch)
        return torch.stack(x_batch, dim=0), torch.tensor(y_batch, dtype=torch.long)

    def __len__(self):
        return len(self.buffer)

# ------------------------- EWC -------------------------
class EWC:
    def __init__(self, model, dataloader, device, fisher_sample_size=200):
        self.model = model
        self.device = device
        self.fisher_sample_size = fisher_sample_size
        self.params = {n: p for n, p in model.named_parameters() if p.requires_grad}
        self._means = {}
        self._precision_matrices = {}
        self._compute_fisher(dataloader)

    def _compute_fisher(self, dataloader):
        for n, p in self.params.items():
            self._precision_matrices[n] = torch.zeros_like(p)
            self._means[n] = p.data.clone()

        self.model.eval()
        n_batches = 0
        samples_seen = 0
        for x, y in dataloader:
            if samples_seen >= self.fisher_sample_size:
                break
            x, y = x.to(self.device), y.to(self.device)
            self.model.zero_grad()
            output = self.model(x)
            loss = nn.functional.cross_entropy(output, y)
            loss.backward()
            for n, p in self.params.items():
                if p.grad is not None:
                    self._precision_matrices[n] += p.grad.data ** 2
            n_batches += 1
            samples_seen += x.size(0)

        for n in self._precision_matrices:
            if n_batches > 0:
                self._precision_matrices[n] /= n_batches

    def penalty(self, model):
        loss = 0.0
        for n, p in model.named_parameters():
            if n in self._precision_matrices:
                loss += (self._precision_matrices[n] * (p - self._means[n]) ** 2).sum()
        return loss

# ------------------------- TRAINING -------------------------
def train_epoch(model, train_loader, val_loader, config, epochs, tag, ewc=None, buffer=None):
    optimizer = torch.optim.Adam(model.parameters(), lr=config.lr, weight_decay=config.weight_decay)
    criterion = nn.CrossEntropyLoss()

    for epoch in range(epochs):
        model.train()
        running_loss, correct, total = 0.0, 0, 0

        for x, y in tqdm(train_loader, desc=f'{tag} Epoch {epoch+1}'):
            x, y = x.to(config.device), y.to(config.device)

            # --- Replay buffer: sample old examples ---
            x_replay, y_replay = None, None  # Initialize to avoid UnboundLocalError
            if buffer is not None and len(buffer) > 0:
                x_replay, y_replay = buffer.sample(config.replay_batch_size)
                if x_replay is not None:
                    x_replay = x_replay.to(config.device)
                    y_replay = y_replay.to(config.device)
                    x = torch.cat([x, x_replay], dim=0)
                    y = torch.cat([y, y_replay], dim=0)

            optimizer.zero_grad()
            out = model(x)
            loss = criterion(out, y)

            # EWC penalty
            if ewc is not None:
                loss += config.ewc_lambda * ewc.penalty(model)

            loss.backward()
            optimizer.step()

            running_loss += loss.item()
            correct += (out.argmax(1) == y).sum().item()
            total += y.size(0)

            # --- Store samples in replay buffer ---
            if buffer is not None:
                # Determine how many original (non-replay) samples were in the batch
                if x_replay is not None and y_replay is not None:
                    orig_len = len(y) - len(y_replay)
                else:
                    orig_len = len(y)
                for i in range(orig_len):
                    buffer.push(x[i], y[i])

        train_acc = correct / total
        val_acc, _ = evaluate(model, val_loader, config)
        print(f"  {tag} Epoch {epoch+1}: train_acc={train_acc:.4f}, val_acc={val_acc:.4f}")

def evaluate(model, dataloader, config):
    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for x, y in dataloader:
            x = x.to(config.device)
            out = model(x)
            pred = out.argmax(dim=1).cpu()
            all_preds.extend(pred.numpy())
            all_labels.extend(y.numpy())
    acc, f1 = compute_metrics(all_preds, all_labels)
    return acc, f1

# ------------------------- RUN EXPERIMENT -------------------------
def run_experiment(config, strategy):
    set_seed(config.seed)
    model = StrokeCNN(num_classes=config.num_classes).to(config.device)
    buffer = ReplayBuffer(config.buffer_capacity) if 'replay' in strategy else None

    all_accs = []

    for task_id in range(2):
        print(f"\n--- Strategy: {strategy} | Task {task_id+1} ---")

        train_loader = get_dataloaders(config, task_id, split='train')
        val_loader = get_dataloaders(config, task_id, split='val')

        ewc = None
        if ('ewc' in strategy) and task_id == 1:
            task0_loader = get_dataloaders(config, 0, split='train')
            ewc = EWC(model, task0_loader, config.device, config.fisher_sample_size)
            print(f"EWC penalty lambda: {config.ewc_lambda}")

        train_epoch(model, train_loader, val_loader, config, config.epochs_per_task,
                    tag=f"{strategy}/T{task_id+1}", ewc=ewc, buffer=buffer)

        # Evaluate on both tasks
        accs = []
        for tid in range(2):
            # FIXED: correct function name and no unpacking (returns one DataLoader)
            val_loader_tid = get_dataloaders(config, tid, split='val')
            # evaluate returns (acc, f1) – take the first value
            acc = evaluate(model, val_loader_tid, config)[0]
            accs.append(acc)
        all_accs.append(accs)
        print(f"  After Task {task_id+1}: Accuracy on Task0={accs[0]:.4f}, Task1={accs[1]:.4f}")

        save_checkpoint(model, None, task_id,
                        os.path.join(config.model_dir, f"{strategy}_task{task_id}.pt"))

    return all_accs

